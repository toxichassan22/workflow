NAVY = RGBColor(0x1F, 0x3A, 0x5F)
GRAY = RGBColor(0x59, 0x59, 0x59)


def set_rtl(paragraph):
    pPr = paragraph._p.get_or_add_pPr()
    bidi = OxmlElement("w:bidi")
    bidi.set(qn("w:val"), "1")
    pPr.append(bidi)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT


def style_run(run, size=12, bold=False, color=None):
    run.font.name = "Arial"
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color
    rPr = run._r.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn("w:cs"), "Arial")
    cs_size = OxmlElement("w:szCs")
    cs_size.set(qn("w:val"), str(size * 2))
    rPr.append(cs_size)
    run.font.rtl = True


def add_par(doc, text, size=12, bold=False, color=None, space_after=6, indent=0):
    p = doc.add_paragraph()
    set_rtl(p)
    p.paragraph_format.space_after = Pt(space_after)
    if indent:
        p.paragraph_format.right_indent = Cm(indent)
    r = p.add_run(text)
    style_run(r, size=size, bold=bold, color=color)
    return p


def add_rule(doc):
    p = doc.add_paragraph()
    set_rtl(p)
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "6")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "C8C8C8")
    pBdr.append(bottom)
    pPr.append(pBdr)
    p.paragraph_format.space_after = Pt(10)


